use anyhow::{Context, Result};
use clap::Parser;
use crossbeam::channel::{self, Receiver, Sender};
use std::error::Error;
use std::io::{BufReader, BufWriter, Write};
use std::net::{TcpListener, TcpStream};
use std::thread;
use std::time::Duration;

use bunshin::{
    State,
    machine::Machine,
    protocol::{Packet, Rpc},
};

#[derive(Parser, Debug, Clone)]
#[command(author, version, about)]
struct Cli {
    #[arg(short, long)]
    port: u64,

    #[arg(short, long)]
    node_id: u64,

    #[arg(long, value_delimiter = ',')]
    peers: Option<Vec<String>>,
}

fn main() -> Result<()> {
    let args = Cli::parse();
    let address = format!("localhost:{}", args.port);

    let peers = match parse_peers(&address, args.peers) {
        Ok(peers) => peers,
        Err(err) => {
            eprintln!("failed to parse peer addresses: {}", err);
            return Ok(());
        }
    };

    let mut machine = Machine::default(args.node_id, peers);
    let (network_tx, mut network_rx) = channel::unbounded::<Packet>();
    let (done_tx, done_rx) = channel::unbounded();

    std::thread::spawn(move || {
        println!("state-machine started");
        let mut state = State::new(args.node_id);
        machine.run(&mut state, &mut network_rx);
        println!("state-machine has being shutdown");
        if let Err(err) = done_tx.send(()) {
            eprintln!("failed to shutdown main server: {}", err)
        };
    });

    start_server(address.clone(), network_tx, done_rx);

    Ok(())
}

/// note: this part was generated by claude to include non-blocking behaviour
/// to tell the server to stop when the internal state had shutdown
pub fn start_server(addr: String, sender: Sender<Packet>, done: Receiver<()>) {
    let listener = TcpListener::bind(&addr).unwrap();
    listener.set_nonblocking(true).unwrap();
    let (stop_tx, stop_rx) = channel::bounded::<()>(1);

    while stop_rx.try_recv().is_err() && done.try_recv().is_err() {
        match listener.accept() {
            Ok((conn, _)) => {
                conn.set_nonblocking(false).unwrap();
                let (sender, stop_tx) = (sender.clone(), stop_tx.clone());
                thread::spawn(move || {
                    if let Err(e) = handle_conn(conn, sender) {
                        println!("connection_error:: {:?}", e);
                        let _ = stop_tx.try_send(());
                    }
                });
            }
            Err(_) => thread::sleep(Duration::from_millis(20)),
        }
    }

    println!("server shutdown")
}

fn handle_conn(
    conn: TcpStream,
    state_sender: Sender<Packet>,
) -> Result<(), Box<dyn std::error::Error>> {
    let reader = BufReader::new(conn.try_clone().unwrap());
    let mut writer = BufWriter::new(conn);

    let parser = serde_json::Deserializer::from_reader(reader);
    for msg in parser.into_iter::<Rpc>() {
        let rpc_msg = match msg {
            Ok(m) => m,
            Err(ref err) => {
                println!("error parsing message {:?}, {:?}", err, msg);
                continue;
            }
        };

        let (sender, recv) = channel::unbounded::<Rpc>();

        let envelope = Packet {
            rpc: rpc_msg,
            sender,
        };

        match state_sender.send(envelope) {
            Ok(_) => {}
            Err(err) => {
                println!("INTERNAL STATE IS DOWN. Failed to send: {}", err);
                return Err(format!("INTERNAL STATE IS DOWN. Failed to send: {}", err).into());
            }
        };
        let rpc_reply = recv.recv_timeout(Duration::from_secs(5)).unwrap();
        serde_json::to_writer(&mut writer, &rpc_reply).unwrap();
        writer.write_all(b"\n")?;
        writer.flush()?;
    }
    Ok(())
}

/// Validates all peer addresses as valid IP addresses and the listen address
/// of this node is not included as a peer
fn parse_peers(
    listen_addr: &String,
    raw_peer: Option<Vec<String>>,
) -> Result<Vec<String>, Box<dyn Error>> {
    use std::net::ToSocketAddrs;
    let peers = if let Some(peers) = raw_peer {
        peers
    } else {
        return Ok(Vec::new());
    };

    if peers.is_empty() {
        return Ok(peers);
    }

    let mut parsed_addrs = vec![];

    for (idx, port) in peers.as_slice().iter().enumerate() {
        let addr = format!("localhost:{}", port);
        if addr == listen_addr.as_str() {
            let msg = format!("cannot use self.addr as a peer at index: {}", idx);
            return Err(msg.into());
        }
        addr.as_str()
            .to_socket_addrs()?
            .next()
            .context("invalid address provided for peer")?;

        parsed_addrs.push(addr)
    }

    Ok(parsed_addrs)
}
